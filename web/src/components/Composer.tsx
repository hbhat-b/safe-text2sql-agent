"use client";

import { ArrowUp } from "lucide-react";
import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";

export function Composer({ busy, onSend }: { busy: boolean; onSend: (q: string) => void }) {
  const [value, setValue] = useState("");

  const submit = () => {
    if (!value.trim() || busy) return;
    onSend(value);
    setValue("");
  };

  return (
    <div className="px-4 pt-2 pb-3 sm:px-5">
      <form
        className="mx-auto flex max-w-3xl items-end gap-2 rounded-2xl border bg-card p-2 pl-3 shadow-sm transition-colors focus-within:border-ring"
        onSubmit={(e) => {
          e.preventDefault();
          submit();
        }}
      >
        {/* field-sizing-content makes the textarea grow with its content. */}
        <Textarea
          rows={1}
          value={value}
          placeholder="Ask a question about the music store data…"
          onChange={(e) => setValue(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) {
              e.preventDefault();
              submit();
            }
          }}
          maxLength={500}
          autoFocus
          className="max-h-44 min-h-9 resize-none border-0 bg-transparent px-0 py-1.5 shadow-none focus-visible:ring-0 dark:bg-transparent"
        />
        <Button type="submit" size="icon" className="rounded-xl" disabled={!value.trim() || busy} aria-label="Send">
          <ArrowUp />
        </Button>
      </form>
      <p className="mx-auto mt-2 max-w-3xl text-center text-[11px] text-muted-foreground">
        Queries are validated and executed read-only. Answers are generated by an LLM and may be wrong.
      </p>
    </div>
  );
}
